# style properties that can carry a color value
COLOR_PROPS = re.compile(
    r"color|background|border|outline|fill|stroke|shadow|caret|column-rule|text-emphasis")
# SVG presentation attributes that colorize without style="...". Lookbehind
# (?<![\w-]) instead of \b so data-fill="…" / x-stroke="…" don't match the
# fill/stroke tail of a hyphenated custom attribute name.
SVG_COLOR_ATTR = re.compile(r"""(?<![\w-])(fill|stroke|stop-color|flood-color|lighting-color)\s*=\s*["']([^"']*)["']""")
SVG_ATTR_ALLOWED = {"none", "currentcolor", "transparent", "inherit"}
# E10 scenario-label markers by outline language — a scenario page must carry a
# VISIBLE "this is illustrative" label; the schema allows language:"en" decks, so
# an English deck labels in English rather than being forced to embed 示意/虚构.
SCENARIO_LABELS = {
    "zh": ("示意", "虚构"), "zh-hans": ("示意", "虚构"), "zh-hant": ("示意", "虛構"),
    "en": ("illustrative", "sample", "scenario", "not real", "for illustration"),
}
SCENARIO_LABELS_ANY = tuple(m for ms in SCENARIO_LABELS.values() for m in ms)


def named_color_hits(style_text: str) -> list[str]:
    """Named-color literals inside color-capable declarations of style attrs.

    var(--c-gold) and url(images/navy-bg.png) are stripped first: a color word
    inside a token name (validated separately by E3) or an image filename is not
    a literal color and must not trip the gate."""
    hits = []
    for decl in style_text.split(";"):
        prop, _, value = decl.partition(":")
        if not value or not COLOR_PROPS.search(prop.strip().lower()):
            continue
        clean = re.sub(r"var\([^)]*\)|url\([^)]*\)", " ", value.lower())
        for tok in re.findall(r"[a-zA-Z]+", clean):
            if tok in NAMED_COLORS:
                hits.append(f"{prop.strip()}: {tok}")
    return hits


def valid_layouts() -> set[str]:
    """Layout registry SSOT is layouts.html — parse it so adding S11 there
    can never desync this hard gate. Fallback: S01–S10."""
    reg = SKILL_DIR / "assets" / "templates" / "layouts.html"
    if reg.is_file():
        found = set(re.findall(r'data-layout="(S\d{2})"', reg.read_text(encoding="utf-8")))
        if found:
            return found
    return {f"S{i:02d}" for i in range(1, 11)}


def page_no(p: Path) -> int:
    m = re.search(r"(\d+)", p.stem)
    return int(m.group(1)) if m else 0


def main() -> int:
    args = [x for x in sys.argv[1:] if x != "--single"]
    single = "--single" in sys.argv[1:]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    proj = Path(args[0])
    pages = sorted((proj / "pages").glob("page-*.html"), key=page_no)
    tokens_f = proj / "tokens.css"
    if not pages or not tokens_f.is_file():
        print(f"ERROR: need {proj}/pages/page-*.html and tokens.css", file=sys.stderr)
        return 2

    allowed_vars = set(re.findall(r"(--[\w-]+)\s*:", tokens_f.read_text(encoding="utf-8")))
    layouts_registry = valid_layouts()
    outline = {}
    outline_f = proj / "outline.json"
    lang = "zh"
    if outline_f.is_file():
        try:
            data = json.loads(outline_f.read_text(encoding="utf-8"))
            outline = {s["index"]: s for s in data.get("slides", []) if "index" in s}
            lang = str(data.get("language") or "zh").lower()
        except (json.JSONDecodeError, KeyError, TypeError):
            print("WARN: outline.json unreadable — skipping cross-checks")
    # accept the language's own markers; fall back to any known marker so a
    # bilingual label ("示意 / illustrative") always satisfies E10
    scenario_markers = SCENARIO_LABELS.get(lang) or SCENARIO_LABELS_ANY

    errors: list[str] = []
    warns: list[str] = []
    layouts: list[str] = []

    for p in pages:
        n = page_no(p)
        t = p.read_text(encoding="utf-8")
        body = re.sub(r"<!--.*?-->", "", t, flags=re.S)
        # Match single- OR double-quoted style attrs, with optional spaces around
        # `=` — Chrome renders `style='…'` and `style = "…"` identically, so a
        # double-quote-only regex would let literal colors / font-sizes / gradients /
        # opacity:0 hides silently escape E1/E2/E4/E9 (a real gate-dodge).
        style_text = " ".join(re.findall(r'style\s*=\s*["\']([^"\']*)["\']', body))
        visible = re.sub(r"<[^>]+>", " ", body)

        # E8 fragment shape — export splitting and shell styling both rely on it.
        # Close tags counted too: a stray </section> would make split_pages
        # silently truncate the page tail in every derivative.
        n_open = len(re.findall(r"<section\b", body))
        n_close = len(re.findall(r"</section>", body))
        if n_open != 1 or n_close != 1:
            errors.append(f"E8 {p.name}: expected exactly one <section>…</section>, "
                          f"found {n_open} open / {n_close} close")
        sec_tag = re.search(r"<section\b[^>]*>", body)
        if sec_tag and not re.search(r'class="[^"]*\bslide\b[^"]*"', sec_tag.group(0)):
            errors.append(f"E8 {p.name}: <section> missing the \"slide\" class")

        for m in re.findall(r"#[0-9a-fA-F]{3,8}\b|rgba?\(|hsla?\(", style_text):
            errors.append(f"E1 {p.name}: literal color {m}")
        for hit in named_color_hits(style_text):
            errors.append(f"E1 {p.name}: literal named color ({hit})")
        for attr, val in SVG_COLOR_ATTR.findall(body):
            if val.strip().lower() not in SVG_ATTR_ALLOWED:
                errors.append(f"E1 {p.name}: literal color in SVG attribute {attr}=\"{val}\" "
                              f"(use currentColor and color the parent via var)")
        for m in re.findall(r"font-size:\s*([\d.]+(?:px|pt|em|rem|vw|vh|vmin|vmax|ch|ex|%))",
                            style_text):
            errors.append(f"E2 {p.name}: literal font-size {m}")
        if HIDDEN_STYLE.search(style_text):
            errors.append(f"E9 {p.name}: hidden content (display:none/visibility:hidden/"
                          f"opacity:0) — nothing on a static slide may be invisible")
        for m in re.findall(r"var\((--[\w-]+)\)", style_text):
            if m not in allowed_vars:
                errors.append(f"E3 {p.name}: unknown var {m}")
        for rx, label in FORBIDDEN_STYLE:
            if rx.search(style_text):
                errors.append(f"E4 {p.name}: forbidden {label}")
        for rx, label in FORBIDDEN_TAGS:
            if rx.search(body):
                errors.append(f"E4 {p.name}: forbidden {label}")

        lay = re.search(r'data-layout="([\w-]+)"', body)
        ryt = re.search(r'data-rhythm="([\w-]+)"', body)
        lay_v = lay.group(1) if lay else None
        ryt_v = ryt.group(1) if ryt else None
        if lay_v not in layouts_registry:
            errors.append(f"E5 {p.name}: data-layout={lay_v!r} not in registry {sorted(layouts_registry)}")
        if ryt_v not in VALID_RHYTHMS:
            errors.append(f"E5 {p.name}: data-rhythm={ryt_v!r} invalid")
        layouts.append(lay_v or "?")
        if n in outline:
            want_lay, want_ryt = outline[n].get("layout"), outline[n].get("rhythm")
            if want_lay and lay_v != want_lay:
                errors.append(f"E5 {p.name}: layout {lay_v} != outline {want_lay}")
            if want_ryt and ryt_v != want_ryt:
                errors.append(f"E5 {p.name}: rhythm {ryt_v} != outline {want_ryt}")
            # E10 — scenario (fictional) data pages promise a visible 「示意」 label;
            # E9 above guarantees "in the text" means "actually visible"
            evs = outline[n].get("evidence") or []
            if (isinstance(evs, list)
                    and any(isinstance(ev, dict) and ev.get("scenario") is True for ev in evs)
                    and not any(m in visible.lower() if m.isascii() else m in visible
                                for m in scenario_markers)):
                errors.append(f"E10 {p.name}: scenario data page must render a visible "
                              f"scenario label {scenario_markers} "
                              f"(outline marks its evidence scenario:true)")

        for rx in PLACEHOLDER_RES:
            if rx.search(visible):
                errors.append(f"E6 {p.name}: placeholder residue ({rx.pattern})")
                break

        for m in re.findall(r"(?:margin|padding|gap)[^:;]*:\s*([\d]+)px", style_text):
            if int(m) % 8 != 0:
                warns.append(f"W1 {p.name}: {m}px off the 8px module")
        if ryt_v == "breathing":
            vlen = len(re.sub(r"\s+", "", visible))
            if vlen > 120:
                warns.append(f"W2 {p.name}: breathing page has {vlen} chars of text")

    if not single:
        # E5 — contiguous 1..N page numbers: shots/pptx/notes alignment maps
        # list position to page number, so holes would silently shift them all
        nums = [page_no(p) for p in pages]
        if nums != list(range(1, len(pages) + 1)):
            errors.append(f"E5 page numbers not contiguous 1..{len(pages)}: {nums}")
        # schema contract: >=8 pages need >=6 distinct layouts (small decks are
        # free to repeat — forcing variety on a 5-pager degrades, not improves)
        distinct = len(set(layouts))
        if len(pages) >= 8 and distinct < 6:
            errors.append(f"E7 layout diversity: {distinct} distinct < 6 required for {len(pages)} pages")
        run = max(len(list(g)) for _, g in itertools.groupby(layouts))
        if run >= 3:
            errors.append(f"E7 {run} consecutive pages share one layout (max 2)")
        if outline and set(nums) != set(outline):
            errors.append(f"E5 page numbers {sorted(set(nums))} != outline indexes {sorted(outline)}")

    for w in warns:
        print("WARN ", w)
    for e in errors:
        print("ERROR", e)

    # qa_report.json aggregation — the "structure" section; probe_overflow.py
    # appends its own section. Receipt rule: pages listed must equal pages seen.
    report_f = proj / "qa_report.json"
    report = {}
    if report_f.is_file():
        try:
            report = json.loads(report_f.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            report = {}
    report["structure"] = {
        "mode": "single" if single else "full",
        "pages": [page_no(p) for p in pages],
        "layouts": layouts,
        "errors": errors,
        "warnings": warns,
    }
    report_f.write_text(json.dumps(report, ensure_ascii=False, indent=1), encoding="utf-8")

    print(f"validate: {len(pages)} pages · layouts={layouts} · {len(errors)} errors · {len(warns)} warnings")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
