#!/usr/bin/env python3
"""deckcraft QA gate — validate page fragments against the spec_lock contract.

    python3 validate_deck.py <project_dir> [--single]

  --single   first-page-gate mode: skip deck-level checks (E7 diversity,
             page-count vs outline) so a lone probe page can be validated
             before fanning out the rest.

Style rules are checked against style="..." attribute contents only — visible
text is free to mention "Gradient Descent", HTML entities (&#8212;), issue
numbers (#123) etc. without tripping the gate.

Checks (ERROR fails the gate, WARN is advisory):
  E1 literal colors in style attributes or SVG presentation attributes —
     hex/rgb/hsl AND CSS named colors (white/crimson/…); palette vars only
  E2 literal font-size in any unit (px/pt/em/rem/vw/…) — ramp vars only
  E3 var() reference not defined in tokens.css
  E4 forbidden styling: gradient (incl. SVG <linearGradient>/<radialGradient>),
     box-shadow, italic, underline decoration; <script>/<style> tags
  E5 data-layout/data-rhythm missing, unknown (registry = layouts.html), or
     mismatching outline.json; page numbers not contiguous 1..N or != outline
  E6 placeholder residue / generator signatures in visible text
  E7 layout diversity: >=8 pages need >=6 distinct; 3+ consecutive same layout
  E8 fragment shape: not exactly one <section> (open AND close), "slide" class
  E9 hidden content (display:none/visibility:hidden/opacity:0) — nothing on a
     static 1280x720 slide may be invisible (also defeats hiding gate-dodges)
  E10 scenario pages (per outline evidence) must carry a VISIBLE 「示意」 label
  W1 style margin/padding/gap not on the 8px module (border widths exempt)
  W2 breathing page unusually text-heavy (> 120 visible chars)

Exit 0 = pass (warnings allowed), 1 = errors found, 2 = usage/setup problem.
"""
from __future__ import annotations

import itertools
import json
import re
import sys
from pathlib import Path

from console_encoding import configure_utf8_stdio

configure_utf8_stdio()

SKILL_DIR = Path(__file__).resolve().parent.parent
VALID_RHYTHMS = {"anchor", "dense", "breathing"}
# Placeholder scan runs on visible text: word-boundary + uppercase TODO so
# "Todoist"/"todos" don't trip it; lorem/ipsum stay case-insensitive.
PLACEHOLDER_RES = [
    re.compile(r"\blorem\b|\bipsum\b", re.I),
    re.compile(r"\bTODO\b(?!-)"),  # (?!-) exempts compounds like "TODO-list 工具"
    re.compile(r"待补充|\[insert|占位符"),
    # generator watermark/signature — narrow to explicit tool attribution so
    # legit prose ("revenue generated by Q3", "自动生成代码") doesn't trip it
    re.compile(r"(?:generated|made|created)\s+(?:by|with)\s+"
               r"(?:deckcraft|ai|gpt|claude|chatgpt)\b"
               r"|由\s*(?:AI|GPT|Claude|大模型|deckcraft)\s*生成", re.I),
]
# Style-attribute-scoped forbidden rules (E4).
FORBIDDEN_STYLE = [
    (re.compile(r"gradient", re.I), "gradient"),
    (re.compile(r"box-shadow"), "box-shadow"),
    (re.compile(r"font-style:\s*italic"), "italic (CJK 禁假斜体)"),
    (re.compile(r"text-decoration:\s*underline"), "underline decoration"),
]
FORBIDDEN_TAGS = [
    (re.compile(r"<script", re.I), "script tag"),
    (re.compile(r"<style", re.I), "style tag (tokens live in tokens.css only)"),
    (re.compile(r"<(?:linear|radial)Gradient\b", re.I), "SVG gradient element"),
]
HIDDEN_STYLE = re.compile(r"display\s*:\s*none|visibility\s*:\s*hidden|opacity\s*:\s*0(?![.\d])")
# CSS named colors (full keyword list) — a literal color is a literal color
# whether it's spelled #dc143c or crimson; only var(--c-*) may color anything.
